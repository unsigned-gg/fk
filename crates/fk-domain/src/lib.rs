//! Zero-I/O domain models for `fk`.
//!
//! Provides deterministic trace generation, corpus accounting,
//! and agent orchestration lifecycle assertions.

use serde::{Deserialize, Serialize};

/// Core state representation for `fk`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FkState {
    /// Protocol version.
    pub version: u32,
    /// Identifier.
    pub id: String,
    /// Number of generated traces.
    pub trace_count: u64,
}

impl Default for FkState {
    fn default() -> Self {
        Self {
            version: 1,
            id: String::from("initial"),
            trace_count: 0,
        }
    }
}

/// Represents an execution trace record generated by an agent.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TraceRecord {
    pub trace_id: String,
    pub session_id: String,
    pub step_index: u64,
    pub elapsed_ms: u64,
}

impl TraceRecord {
    pub fn new(trace_id: impl Into<String>, session_id: impl Into<String>, step_index: u64) -> Self {
        Self {
            trace_id: trace_id.into(),
            session_id: session_id.into(),
            step_index,
            elapsed_ms: 0,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_state() {
        let state = FkState::default();
        assert_eq!(state.version, 1);
        assert_eq!(state.id, "initial");
        assert_eq!(state.trace_count, 0);
    }

    #[test]
    fn test_trace_record() {
        let rec = TraceRecord::new("tr-001", "sess-100", 42);
        assert_eq!(rec.trace_id, "tr-001");
        assert_eq!(rec.step_index, 42);
    }
}
